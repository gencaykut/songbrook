/// The English keys with catalog translations, so tests can check that every
/// one also has a Turkish translation.
Iterable<String> get appStringTranslationKeys => _appStringTranslations.keys;

const Map<String, int> _appStringLanguageIndex = <String, int>{
  'pt': 0,
  'fr': 1,
  'ko': 2,
  'zh': 3,
  'ja': 4,
};

final List<_AppStringTranslationTemplate> _dynamicAppStringTranslations = () {
  final entries = _appStringTranslations.entries
      .where((entry) => entry.key.contains('ZXQPH'))
      .toList();
  entries.sort((left, right) => right.key.length.compareTo(left.key.length));
  return entries.map(_AppStringTranslationTemplate.new).toList(growable: false);
}();

String? translateAppString(String english, String languageCode) {
  if (languageCode == 'tr') return translateTurkishAppString(english);
  final index = _appStringLanguageIndex[languageCode];
  if (index == null) return null;
  final exact = _appStringTranslations[english];
  if (exact != null) return exact[index];
  for (final template in _dynamicAppStringTranslations) {
    final match = template.matcher.firstMatch(english);
    if (match == null) continue;
    final substitutions = <int, String>{};
    for (var i = 0; i < template.markerIndexes.length; i++) {
      substitutions[template.markerIndexes[i]] = match.group(i + 1) ?? '';
    }
    return template.translations[index].replaceAllMapped(
      RegExp(r'ZXQPH(\d+)X'),
      (marker) => substitutions[int.parse(marker.group(1)!)] ?? marker[0]!,
    );
  }
  return null;
}

class _AppStringTranslationTemplate {
  _AppStringTranslationTemplate(MapEntry<String, List<String>> entry)
    : translations = entry.value,
      markerIndexes = RegExp(r'ZXQPH(\d+)X')
          .allMatches(entry.key)
          .map((match) => int.parse(match.group(1)!))
          .toList(growable: false),
      matcher = RegExp(_templatePattern(entry.key), dotAll: true);

  final List<String> translations;
  final List<int> markerIndexes;
  final RegExp matcher;
}

String _templatePattern(String template) {
  final marker = RegExp(r'ZXQPH\d+X');
  final chunks = template.split(marker);
  final buffer = StringBuffer('^');
  for (var i = 0; i < chunks.length; i++) {
    buffer.write(RegExp.escape(chunks[i]));
    if (i < chunks.length - 1) buffer.write('(.*?)');
  }
  buffer.write(r'$');
  return buffer.toString();
}
